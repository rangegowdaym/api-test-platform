package com.qa.platform;

import static org.testng.Assert.assertEquals;
import static org.testng.Assert.assertTrue;

import com.qa.platform.codegen.ServiceGenerator;
import com.qa.platform.codegen.StepGenerator;
import com.qa.platform.feature.FeatureWriter;
import com.qa.platform.generate.CaseGenerator;
import com.qa.platform.model.TestCase;
import java.util.List;
import java.util.Map;
import com.qa.platform.ingest.IngestService;
import com.qa.platform.model.ApiModel;
import java.nio.file.Files;
import java.nio.file.Path;
import org.testng.annotations.Test;

/** mvn test -Punit */
public class ServiceGeneratorTest {

  @Test
  public void writesOneApiClassPerTagWithOneMethodPerOperation() throws Exception {
    ApiModel m = new IngestService().ingest("src/test/resources/fixtures/sample-api.yaml", Files.createTempDirectory("i"));
    Path out = Files.createTempDirectory("api");
    ServiceGenerator.Result r = new ServiceGenerator().write(m, out);

    assertEquals(r.classes(), 2);
    assertEquals(r.methods(), 5);
    String orders = Files.readString(out.resolve("OrdersApi.java"));
    assertTrue(orders.startsWith("// GENERATED by api-test-platform from sample-api.yaml ("));
    assertTrue(orders.contains("public final class OrdersApi extends BaseApi"));
    assertTrue(orders.contains("public ApiResponse createOrder(Object body)"));
    assertTrue(orders.contains("public ApiResponse getOrderById(Object orderId)"));
    assertTrue(orders.contains("public ApiResponse listOrders(Map<String, ?> query)"));
    assertTrue(orders.contains(".pathParam(\"orderId\", orderId)"));
    assertTrue(Files.exists(out.resolve("CustomersApi.java")));
  }

  @Test
  public void regeneratingOneSpecLeavesOtherSpecsClassesAlone() throws Exception {
    Path out = Files.createTempDirectory("api");
    Path other = out.resolve("BillingApi.java");
    Files.writeString(other, "// GENERATED by api-test-platform from billing.yaml (tag \"billing\"). Do not edit by hand.\n");
    ApiModel m = new IngestService().ingest("src/test/resources/fixtures/sample-api.yaml", Files.createTempDirectory("i"));
    new ServiceGenerator().write(m, out);
    new ServiceGenerator().write(m, out);                       // second run replaces its own files only
    assertTrue(Files.exists(other));
    assertTrue(Files.exists(out.resolve("OrdersApi.java")));
  }

  @Test
  public void writesOneStepsClassPerTagThatCallsTheGeneratedApi() throws Exception {
    ApiModel m = new IngestService().ingest("src/test/resources/fixtures/sample-api.yaml", Files.createTempDirectory("i"));
    Path out = Files.createTempDirectory("steps");
    StepGenerator.Result r = new StepGenerator().write(m, out);

    assertEquals(r.classes(), 2);
    assertEquals(r.steps(), 5);
    String orders = Files.readString(out.resolve("OrdersSteps.java"));
    assertTrue(orders.startsWith("// GENERATED by api-test-platform from sample-api.yaml ("));
    assertTrue(orders.contains("package com.qa.automation.steps.generated;"));
    assertTrue(orders.contains("public OrdersSteps(ScenarioContext ctx, ServiceFactory services)"));
    assertTrue(orders.contains("@When(\"I call the orders operation \\\"createOrder\\\"\")"));
    assertTrue(orders.contains(".api(OrdersApi.class)"));
    assertTrue(orders.contains(".getOrderById(call.path(\"orderId\"), call.customize(false, false))"));
    assertTrue(orders.contains(".createOrder(call.body(), call.customize(false, true))"));
    assertTrue(orders.contains(".listOrders(call.query(), call.customize(true, false))"));
  }

  @Test
  public void everyFeatureStepHasAGeneratedStepDefinition() throws Exception {
    ApiModel m = new IngestService().ingest("src/test/resources/fixtures/sample-api.yaml", Files.createTempDirectory("i"));
    List<TestCase> approved = new CaseGenerator().generate(m, CaseGenerator.Options.all()).values().stream()
        .flatMap(List::stream).map(t -> t.withStatus(TestCase.APPROVED)).toList();
    Path steps = Files.createTempDirectory("steps");
    new StepGenerator().write(m, steps);
    StringBuilder all = new StringBuilder();
    try (var files = Files.list(steps)) {
      for (Path f : files.toList()) all.append(Files.readString(f));
    }
    for (Map.Entry<String, String> used : FeatureWriter.usedSteps(approved).entrySet()) {
      // feature text "I call the orders operation "createOrder"" -> annotation literal with escaped quotes
      String annotation = "@When(\"" + used.getKey().replace("\"", "\\\"") + "\")";
      assertTrue(all.toString().contains(annotation), "no step definition for: " + used.getKey());
    }
  }

  @Test
  public void cucumberSpecialCharactersAreEscaped() {
    // feature text stays readable; the @When expression escapes what Cucumber Expressions treat as syntax
    assertEquals(StepGenerator.stepText("orders", "get/{id}"), "I call the orders operation \"get/{id}\"");
    assertEquals(StepGenerator.cucumberLiteral("get/{id} (v2)"), "get\\/\\{id\\} \\(v2\\)");
  }

  @Test
  public void identifiersAreValidJava() {
    // reserved words and leading digits are made safe
    assertEquals(ServiceGenerator.identifier("default"), "defaultValue");
    assertEquals(ServiceGenerator.identifier("2fa-setup"), "_2faSetup");
    assertEquals(ServiceGenerator.identifier("find-by status"), "findByStatus");
  }
}
