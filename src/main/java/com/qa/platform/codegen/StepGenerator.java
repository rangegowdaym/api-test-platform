package com.qa.platform.codegen;

import com.qa.platform.model.ApiModel;
import com.qa.platform.model.Endpoint;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Writes one step-definition class per OpenAPI tag into src/test/java/com/qa/automation/steps/generated/:
 * {@code <Tag>Steps}, one {@code @When} per operation, each calling the matching method of the generated
 * {@code <Tag>Api}. Generated feature files use exactly these steps:
 *
 * <pre>
 *   Given test case "TC-orders-createOrder-positive-1"
 *   When I call the orders operation "createOrder"        <- OrdersSteps#createOrder -> OrdersApi#createOrder
 *   Then the response status should be 201                <- ApiSteps (shared Then steps)
 * </pre>
 *
 * The request values (path params, body, query, headers, auth) still come from the approved JSON test case,
 * prepared by {@code OperationService.prepare}, so editing a case in the UI needs no regeneration.
 * Files are replaced on every run of {@code services}; never edit them (write extra steps in steps/, not here).
 */
public class StepGenerator {

  public static final String PACKAGE = "com.qa.automation.steps.generated";

  public record Result(int classes, int steps, List<Path> files) {}

  /** The step text a feature file uses for an operation; FeatureWriter calls this so both always agree. */
  public static String stepText(String tag, String operationId) {
    return "I call the " + ServiceGenerator.slug(tag) + " operation \"" + operationId.replaceAll("[\\r\\n]+", " ") + "\"";
  }

  public Result write(ApiModel model, Path outDir) throws IOException {
    Files.createDirectories(outDir);
    String marker = "// GENERATED by api-test-platform from " + model.specName() + " (";
    try (Stream<Path> old = Files.list(outDir)) {
      for (Path p : old.filter(f -> f.toString().endsWith("Steps.java")).toList()) {
        if (Files.readString(p).startsWith(marker)) Files.delete(p);
      }
    }
    List<Path> files = new ArrayList<>();
    int steps = 0;
    for (Map.Entry<String, List<Endpoint>> t : ServiceGenerator.byTag(model).entrySet()) {
      String apiClass = ServiceGenerator.className(t.getKey());
      String className = apiClass.substring(0, apiClass.length() - "Api".length()) + "Steps";
      Path f = outDir.resolve(className + ".java");
      if (Files.exists(f) && !Files.readString(f).contains("from " + model.specName() + " (")) {
        throw new IllegalStateException(className + " already exists from another spec (same OpenAPI tag \"" + t.getKey()
            + "\"). Rename the tag in one spec.");
      }
      List<ServiceGenerator.Op> ops = ServiceGenerator.operations(t.getValue());
      Files.writeString(f, render(model.specName(), t.getKey(), className, apiClass, ops));
      files.add(f);
      steps += ops.size();
    }
    return new Result(files.size(), steps, files);
  }

  String render(String specName, String tag, String className, String apiClass, List<ServiceGenerator.Op> ops) {
    StringBuilder sb = new StringBuilder();
    sb.append("// GENERATED by api-test-platform from ").append(specName).append(" (tag \"").append(tag).append("\"). Do not edit by hand.\n");
    sb.append("// Regenerate: java -jar target/api-test-platform.jar services --spec <spec>\n");
    sb.append("package ").append(PACKAGE).append(";\n\n");
    sb.append("import com.qa.automation.api.generated.").append(apiClass).append(";\n");
    sb.append("import com.qa.automation.context.ScenarioContext;\n");
    sb.append("import com.qa.automation.services.OperationService;\n");
    sb.append("import com.qa.automation.services.ServiceFactory;\n");
    sb.append("import io.cucumber.java.en.When;\n\n");
    sb.append("/**\n * When-steps for the operations of tag \"").append(ServiceGenerator.javadoc(tag)).append("\".\n");
    sb.append(" * Each step takes the request from the scenario's test case and sends it through {@link ").append(apiClass).append("}.\n");
    sb.append(" * Then-steps (status, schema, assertions) are shared and live in com.qa.automation.steps.ApiSteps.\n */\n");
    sb.append("public class ").append(className).append(" {\n\n");
    sb.append("  private final ScenarioContext ctx;\n");
    sb.append("  private final ServiceFactory services;\n\n");
    sb.append("  // the only public constructor: PicoContainer injects the scenario's context and services\n");
    sb.append("  public ").append(className).append("(ScenarioContext ctx, ServiceFactory services) {\n");
    sb.append("    this.ctx = ctx;\n    this.services = services;\n  }\n");

    Set<String> expressions = new HashSet<>();
    for (ServiceGenerator.Op op : ops) {
      Endpoint e = op.endpoint();
      String expression = cucumberLiteral(stepText(tag, e.operationId()));
      if (!expressions.add(expression)) continue;   // duplicate operationId in the spec: keep the first

      List<String> args = new ArrayList<>();
      for (ServiceGenerator.PathParam p : op.pathParams()) args.add("call.path(" + ServiceGenerator.javaString(p.name()) + ")");
      if (op.takesBody()) args.add("call.body()");
      if (op.takesQuery()) args.add("call.query()");
      args.add("call.customize(" + op.takesQuery() + ", " + op.takesBody() + ")");

      sb.append("\n  /** ").append(e.method()).append(' ').append(ServiceGenerator.javadoc(e.path()))
          .append(" -> {@link ").append(apiClass).append('#').append(op.method()).append("}. */\n");
      sb.append("  @When(").append(ServiceGenerator.javaString(expression)).append(")\n");
      sb.append("  public void ").append(op.method()).append("() {\n");
      sb.append("    OperationService.Call call = services.operations().prepare(ctx, ")
          .append(ServiceGenerator.javaString(e.operationId())).append(");\n");
      sb.append("    ctx.response = services.asUser(call.auth()).api(").append(apiClass).append(".class)\n");
      sb.append("        .").append(op.method()).append('(').append(String.join(", ", args)).append(");\n");
      sb.append("  }\n");
    }
    sb.append("}\n");
    return sb.toString();
  }

  /** Cucumber Expression that matches {@code text} literally: ( ) { } / \ are escaped with a backslash. */
  public static String cucumberLiteral(String text) {
    StringBuilder sb = new StringBuilder();
    for (char c : text.toCharArray()) {
      if ("(){}/\\".indexOf(c) >= 0) sb.append('\\');
      sb.append(c);
    }
    return sb.toString();
  }
}
