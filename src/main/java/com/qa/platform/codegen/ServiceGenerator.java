package com.qa.platform.codegen;

import com.qa.platform.model.ApiModel;
import com.qa.platform.model.Endpoint;
import com.qa.platform.model.Param;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Writes one endpoint class per OpenAPI tag into src/test/java/com/qa/automation/api/generated/:
 * {@code <Tag>Api extends BaseApi}, one method per operation (plus an overload taking a request customiser).
 * Methods return the raw ApiResponse; assertions and business logic live in hand-written services.
 * Re-run after every spec change; files are fully replaced, so never edit them.
 */
public class ServiceGenerator {

  public static final String PACKAGE = "com.qa.automation.api.generated";
  private static final Set<String> JAVA_KEYWORDS = Set.of(
      "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
      "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if",
      "implements", "import", "instanceof", "int", "interface", "long", "native", "new", "package", "private",
      "protected", "public", "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
      "throw", "throws", "transient", "try", "void", "volatile", "while", "true", "false", "null", "record", "var",
      "yield", "sealed", "permits", "body", "query", "customize");

  public record Result(int classes, int methods, List<Path> files) {}

  public Result write(ApiModel model, Path outDir) throws IOException {
    Files.createDirectories(outDir);
    try (Stream<Path> old = Files.list(outDir)) {
      // only classes generated from THIS spec are replaced; other specs' classes and hand-written files stay
      String marker = "// GENERATED by api-test-platform from " + model.specName() + " (";
      for (Path p : old.filter(f -> f.toString().endsWith("Api.java")).toList()) {
        if (Files.readString(p).startsWith(marker)) Files.delete(p);
      }
    }
    Map<String, List<Endpoint>> byTag = byTag(model);

    List<Path> files = new ArrayList<>();
    int methods = 0;
    for (Map.Entry<String, List<Endpoint>> t : byTag.entrySet()) {
      String className = className(t.getKey());
      Path f = outDir.resolve(className + ".java");
      if (Files.exists(f) && !Files.readString(f).contains("from " + model.specName() + " (")) {
        throw new IllegalStateException(className + " already exists from another spec (same OpenAPI tag \"" + t.getKey()
            + "\"). Rename the tag in one spec, or use --out to generate into another folder.");
      }
      Files.writeString(f, render(model.specName(), t.getKey(), className, t.getValue()));
      files.add(f);
      methods += t.getValue().size();
    }
    return new Result(files.size(), methods, files);
  }

  String render(String specName, String tag, String className, List<Endpoint> endpoints) {
    StringBuilder sb = new StringBuilder();
    sb.append("// GENERATED by api-test-platform from ").append(specName).append(" (tag \"").append(tag).append("\"). Do not edit by hand.\n");
    sb.append("// Regenerate: java -jar target/api-test-platform.jar services --spec <spec>\n");
    sb.append("package ").append(PACKAGE).append(";\n\n");
    sb.append("import com.qa.automation.api.BaseApi;\n");
    sb.append("import com.qa.automation.client.ApiClient;\n");
    sb.append("import com.qa.automation.client.ApiRequest;\n");
    sb.append("import com.qa.automation.client.ApiResponse;\n");
    sb.append("import com.qa.automation.client.HttpMethod;\n");
    sb.append("import java.util.Map;\n");
    sb.append("import java.util.function.Consumer;\n\n");
    sb.append("/** Endpoints of tag \"").append(javadoc(tag)).append("\". Each method returns the raw response; assert in a service or step. */\n");
    sb.append("@SuppressWarnings(\"unused\")\n");
    sb.append("public final class ").append(className).append(" extends BaseApi {\n\n");
    sb.append("  public static final String SERVICE = \"").append(slug(tag)).append("\";\n\n");
    sb.append("  public ").append(className).append("(ApiClient client, String authProfile) { super(client, SERVICE, authProfile); }\n");

    for (Op op : operations(endpoints)) {
      Endpoint e = op.endpoint();
      String method = op.method();
      List<String> params = new ArrayList<>();
      List<String> args = new ArrayList<>();
      StringBuilder chain = new StringBuilder();
      for (PathParam p : op.pathParams()) {
        params.add("Object " + p.javaName());
        args.add(p.javaName());
        chain.append(".pathParam(").append(javaString(p.name())).append(", ").append(p.javaName()).append(")");
      }
      if (op.takesBody()) {
        params.add("Object body");
        args.add("body");
        chain.append(".body(body)");
      }
      if (op.takesQuery()) {
        params.add("Map<String, ?> query");
        args.add("query");
        chain.append(".queryParams(query)");
      }
      String sig = String.join(", ", params);
      String sigWithCustomize = sig.isEmpty() ? "Consumer<ApiRequest.Builder> customize" : sig + ", Consumer<ApiRequest.Builder> customize";
      String callArgs = args.isEmpty() ? "NO_CHANGES" : String.join(", ", args) + ", NO_CHANGES";

      sb.append("\n  /** ").append(e.method()).append(' ').append(javadoc(e.path())).append(" (").append(javadoc(e.operationId())).append(")");
      if (e.summary() != null && !e.summary().isBlank()) sb.append(' ').append(javadoc(e.summary().trim())).append('.');
      sb.append(" Documented responses: ").append(String.join(", ", e.responses().keySet())).append(".");
      if (!e.params("query").isEmpty()) {
        sb.append(" Query: ").append(String.join(", ", e.params("query").stream().map(Param::name).toList())).append('.');
      }
      sb.append(" */\n");
      sb.append("  public ApiResponse ").append(method).append('(').append(sig).append(") { return ")
          .append(method).append('(').append(callArgs).append("); }\n\n");
      sb.append("  public ApiResponse ").append(method).append('(').append(sigWithCustomize).append(") {\n");
      sb.append("    return send(request(HttpMethod.").append(e.method().toUpperCase(Locale.ROOT)).append(", ")
          .append(javaString(e.path())).append(")").append(chain).append(", customize);\n");
      sb.append("  }\n");
    }
    sb.append("}\n");
    return sb.toString();
  }

  /** A path parameter: name in the spec and the Java parameter name used for it. */
  public record PathParam(String name, String javaName) {}

  /** One operation as the generated Api method sees it; StepGenerator uses the same list so names always match. */
  public record Op(Endpoint endpoint, String method, List<PathParam> pathParams, boolean takesBody, boolean takesQuery) {}

  /** Operations of one tag in spec order, with unique Java method names (same order = same names every run). */
  public static List<Op> operations(List<Endpoint> endpoints) {
    Set<String> usedNames = new HashSet<>();
    List<Op> ops = new ArrayList<>();
    for (Endpoint e : endpoints) {
      String method = unique(identifier(e.operationId()), usedNames);
      Set<String> usedParams = new HashSet<>();
      List<PathParam> path = new ArrayList<>();
      for (Param p : e.params("path")) path.add(new PathParam(p.name(), unique(identifier(p.name()), usedParams)));
      ops.add(new Op(e, method, path, e.requestBodySchema() != null, !e.params("query").isEmpty()));
    }
    return ops;
  }

  /** Endpoints grouped by primary OpenAPI tag, in spec order. */
  public static Map<String, List<Endpoint>> byTag(ApiModel model) {
    Map<String, List<Endpoint>> byTag = new LinkedHashMap<>();
    for (Endpoint e : model.endpoints()) byTag.computeIfAbsent(e.primaryTag(), k -> new ArrayList<>()).add(e);
    return byTag;
  }

  /** A Java string literal: quotes, backslashes and control characters escaped. */
  static String javaString(String s) {
    StringBuilder sb = new StringBuilder("\"");
    for (char c : s.toCharArray()) {
      switch (c) {
        case '"' -> sb.append("\\\"");
        case '\\' -> sb.append("\\\\");
        case '\n' -> sb.append("\\n");
        case '\r' -> sb.append("\\r");
        case '\t' -> sb.append("\\t");
        default -> {
          if (c < 0x20) sb.append(String.format("\\u%04x", (int) c));
          else sb.append(c);
        }
      }
    }
    return sb.append('"').toString();
  }

  public static String className(String tag) {
    String id = identifier(tag);
    return Character.toUpperCase(id.charAt(0)) + id.substring(1) + "Api";
  }

  /** "find-by-status", "get /orders/{id}", "2fa" -> "findByStatus", "getOrdersId", "_2fa". */
  public static String identifier(String raw) {
    String[] parts = raw.replaceAll("[^A-Za-z0-9]+", " ").trim().split("\\s+");
    StringBuilder sb = new StringBuilder();
    for (String p : parts) {
      if (p.isEmpty()) continue;
      sb.append(sb.length() == 0 ? Character.toLowerCase(p.charAt(0)) + p.substring(1)
          : Character.toUpperCase(p.charAt(0)) + p.substring(1));
    }
    String id = sb.length() == 0 ? "operation" : sb.toString();
    if (Character.isDigit(id.charAt(0))) id = "_" + id;
    return JAVA_KEYWORDS.contains(id) ? id + "Value" : id;
  }

  static String unique(String name, Set<String> used) {
    String n = name;
    int i = 2;
    while (!used.add(n)) n = name + i++;
    return n;
  }

  static String slug(String tag) { return tag.trim().replaceAll("[^A-Za-z0-9_.-]+", "-"); }

  static String javadoc(String s) { return s.replace("*/", "* /").replace("\n", " "); }
}
