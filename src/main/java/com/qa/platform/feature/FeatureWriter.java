package com.qa.platform.feature;

import com.qa.platform.codegen.StepGenerator;
import com.qa.platform.model.TestCase;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;

/**
 * APPROVED test cases -> Cucumber feature files, one file per tag, one scenario per case.
 * Scenarios stay thin: the request and expectations live in the JSON case, loaded by id at run time,
 * so editing a case in the UI never needs a feature regeneration unless its status changes.
 */
public class FeatureWriter {

  public static final String HEADER = "# GENERATED by api-test-platform from approved test cases. Do not edit by hand.\n"
      + "# Change the test case in the approval UI and run:  java -jar target/api-test-platform.jar features\n"
      + "# 'When I call the <tag> operation' steps come from:   java -jar target/api-test-platform.jar services --spec <spec>\n";

  public record Result(int features, int scenarios, List<Path> files) {}

  /** Step lines this writer would emit for the approved cases, keyed by step text (value: "tag operationId"). */
  public static Map<String, String> usedSteps(List<TestCase> all) {
    Map<String, String> steps = new LinkedHashMap<>();
    all.stream().filter(t -> TestCase.APPROVED.equals(t.status())).sorted(Comparator.comparing(TestCase::id))
        .forEach(t -> steps.put(StepGenerator.stepText(t.tags().get(0), t.source().operationId()),
            t.tags().get(0) + " " + t.source().operationId()));
    return steps;
  }

  public Result write(List<TestCase> all, Path outDir) throws IOException {
    Files.createDirectories(outDir);
    // remove old generated files only (hand-written features elsewhere are untouched)
    try (Stream<Path> old = Files.list(outDir)) {
      for (Path p : old.filter(x -> x.toString().endsWith(".feature")).toList()) {
        if (Files.readString(p).startsWith("# GENERATED")) Files.delete(p);
      }
    }

    Map<String, List<TestCase>> byTag = new LinkedHashMap<>();
    all.stream()
        .filter(t -> TestCase.APPROVED.equals(t.status()))
        .sorted(Comparator.comparing(TestCase::id))
        .forEach(t -> byTag.computeIfAbsent(t.tags().get(0), k -> new ArrayList<>()).add(t));

    List<Path> files = new ArrayList<>();
    int scenarios = 0;
    for (Map.Entry<String, List<TestCase>> e : byTag.entrySet()) {
      Path f = outDir.resolve(slug(e.getKey()) + ".feature");
      Files.writeString(f, render(e.getKey(), e.getValue()));
      files.add(f);
      scenarios += e.getValue().size();
    }
    return new Result(files.size(), scenarios, files);
  }

  String render(String tag, List<TestCase> cases) {
    StringBuilder sb = new StringBuilder(HEADER).append('\n');
    sb.append("@").append(slug(tag)).append(" @api\n");
    sb.append("Feature: ").append(tag).append(" API\n\n");
    sb.append("  Background:\n");
    sb.append("    Given the API under test is reachable\n\n");
    for (TestCase t : cases) {
      sb.append("  ").append(tagLine(t)).append('\n');
      sb.append("  Scenario: ").append(escape(t.title())).append('\n');
      sb.append("    Given test case \"").append(t.id()).append("\"\n");
      String auth = t.request().auth();
      if (auth == null || "none".equals(auth)) sb.append("    And I send no credentials\n");
      else if ("invalid".equals(auth)) sb.append("    And I use invalid credentials\n");
      else sb.append("    And I am authenticated as \"").append(auth).append("\"\n");
      // step defined by the generated <Tag>Steps class (services command) -> generated <Tag>Api
      // (Gherkin comments must be on their own line: a trailing "# ..." would become part of the step text)
      sb.append("    # ").append(t.source().method()).append(' ').append(t.source().path().replace("\n", " ")).append('\n');
      sb.append("    When ").append(StepGenerator.stepText(t.tags().get(0), t.source().operationId())).append('\n');
      sb.append("    Then the response status should be ").append(t.expected().status()).append('\n');
      if (t.expected().schema() != null) sb.append("    And the response should match the documented schema\n");
      if (t.expected().assertions() != null && !t.expected().assertions().isEmpty()) {
        sb.append("    And the response should meet the test case assertions\n");
      }
      if (t.expected().maxResponseTimeMs() != null) {
        sb.append("    And the response time should be under ").append(t.expected().maxResponseTimeMs()).append(" ms\n");
      }
      sb.append('\n');
    }
    return sb.toString();
  }

  private static String tagLine(TestCase t) {
    List<String> tags = new ArrayList<>();
    tags.add("@" + t.id());
    for (String tag : t.tags()) {
      String s = "@" + slug(tag);
      if (!tags.contains(s)) tags.add(s);
    }
    tags.add("@" + t.category().toLowerCase(Locale.ROOT).replace('_', '-'));
    return String.join(" ", tags);
  }

  private static String slug(String s) { return s.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "-").replaceAll("^-|-$", ""); }

  private static String escape(String s) { return s.replace("\n", " ").replace("#", "no."); }
}
